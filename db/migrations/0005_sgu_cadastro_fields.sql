-- =============================================================================
-- 0005_sgu_cadastro_fields.sql
-- Ajuste do cadastro do prestador para acomodar os 20 campos do cadastro SGU 2.0.
-- Aditiva e idempotente (ADD COLUMN IF NOT EXISTS / CREATE TABLE IF NOT EXISTS).
--
-- Mapa SGU -> schema (campos que faltavam):
--   4  Tipo do Prestador ........ providers.provider_type
--   5  Área de atuação (PF) ...... providers.area_atuacao
--   11 E-mail (Endereços-CNES) ... provider_locations.email
--   12-20 Certificações/ISO/Acreditação ... provider_certifications (tabela nova)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- providers: tipo do prestador (campo 4) e área de atuação (campo 5)
-- -----------------------------------------------------------------------------
-- provider_type SEM CHECK de propósito: a carga do SGU não pode quebrar por
-- variação de grafia; a normalização fica na camada de import (WS2).
-- Valores esperados (7 tipos do SGU):
--   'CLINICA COOPERADO', 'CLINICA CREDENCIADO', 'HOSPITAL', 'LABORATORIO',
--   'MEDICO COOPERADO', 'MEDICO CREDENCIADO', 'MEDICO PLANTONISTA'
ALTER TABLE providers
  ADD COLUMN IF NOT EXISTS provider_type text,           -- campo 4 (chave do vínculo de roteiros)
  ADD COLUMN IF NOT EXISTS area_atuacao  text;           -- campo 5 (Pessoa Física)

-- Índice para filtrar prestadores por tipo (guia médico, vínculo de roteiros).
CREATE INDEX IF NOT EXISTS providers_provider_type_idx ON providers (provider_type);

-- -----------------------------------------------------------------------------
-- provider_locations: e-mail de contato (campo 11, vem em "Endereços - CNES")
-- -----------------------------------------------------------------------------
ALTER TABLE provider_locations
  ADD COLUMN IF NOT EXISTS email text;                   -- campo 11

-- -----------------------------------------------------------------------------
-- provider_certifications: certificações acadêmicas, ISO 9001 e acreditação
-- (campos 12-20). Uma linha por certificação; 'kind' discrimina o tipo.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS provider_certifications (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id   bigint NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  kind          text NOT NULL,        -- mestrado|doutorado|pos_doc|pos_graduacao|iso_9001|acreditacao
  title         text,                 -- nome do curso/certificado (campos 12-14)
  issuer        text,                 -- instituição de ensino / instituição acreditadora (campos 12-14, 16)
  level         text,                 -- nível da acreditação (campo 17)
  issued_date   date,                 -- data do certificado / data de acreditação (campos 15, 18)
  expiry_date   date,                 -- data de validade (campos 15, 19)
  validated     boolean,              -- validação da instituição acreditadora (campo 20)
  source        text NOT NULL DEFAULT 'sgu', -- 'sgu' | 'manual'
  sgu_synced_at timestamptz,          -- último upsert vindo do SGU
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS provider_certifications_provider_idx ON provider_certifications (provider_id);
CREATE INDEX IF NOT EXISTS provider_certifications_kind_idx     ON provider_certifications (kind);
