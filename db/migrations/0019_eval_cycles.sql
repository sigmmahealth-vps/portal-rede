-- 0019_eval_cycles.sql
-- Introduz o conceito de ciclo (janela temporal) para o motor eval_*.
-- Só um ciclo pode estar 'active=true' por vez (partial unique index).
-- Backfill: instâncias antigas caem no ciclo 2026 (o ativo pós-migration).

CREATE TABLE IF NOT EXISTS eval_cycles (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label       text NOT NULL,
  start_date  date NOT NULL,
  end_date    date NOT NULL,
  active      boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date >= start_date)
);
CREATE UNIQUE INDEX IF NOT EXISTS eval_cycles_one_active
  ON eval_cycles (active) WHERE active;

ALTER TABLE eval_instances
  ADD COLUMN IF NOT EXISTS cycle_id bigint REFERENCES eval_cycles(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS eval_instances_cycle_idx
  ON eval_instances (cycle_id);

-- Seed idempotente: só insere se ainda não houver nenhum ciclo.
INSERT INTO eval_cycles (label, start_date, end_date, active)
SELECT 'Ciclo 2026', DATE '2026-01-01', DATE '2026-12-31', true
WHERE NOT EXISTS (SELECT 1 FROM eval_cycles);

-- Backfill: qualquer instância órfã vai para o único ciclo existente.
UPDATE eval_instances SET cycle_id = (SELECT id FROM eval_cycles ORDER BY id LIMIT 1)
 WHERE cycle_id IS NULL;
