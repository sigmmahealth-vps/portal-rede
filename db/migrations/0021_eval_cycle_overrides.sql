-- 0021_eval_cycle_overrides.sql
-- 5.4.2.1 — override do roteiro por prestador×local dentro de um ciclo.
-- Sem linha aqui → usa o roteiro do grupo (eval_cycle_groups). Com linha → sobrescreve.

CREATE TABLE IF NOT EXISTS eval_cycle_overrides (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id     bigint NOT NULL REFERENCES eval_cycles(id) ON DELETE CASCADE,
  provider_id  bigint NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  location_id  bigint NOT NULL REFERENCES provider_locations(id) ON DELETE CASCADE,
  script_id    bigint NOT NULL REFERENCES eval_scripts(id),
  UNIQUE (cycle_id, provider_id, location_id)
);
CREATE INDEX IF NOT EXISTS eval_cycle_overrides_cycle_idx
  ON eval_cycle_overrides (cycle_id);
