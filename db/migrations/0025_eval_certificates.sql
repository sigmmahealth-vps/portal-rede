-- 0025_eval_certificates.sql
-- Certificado de Qualificação (spec 5.4.5). Um certificado por instância
-- aprovada; verify_code é o código público de autenticidade (QR).
-- Validade = end_date do ciclo + 1 ano (fallback: completed_at + 1 ano).

CREATE TABLE IF NOT EXISTS eval_certificates (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id  bigint NOT NULL UNIQUE REFERENCES eval_instances(id) ON DELETE CASCADE,
  verify_code  text   NOT NULL UNIQUE,   -- 32 chars hex aleatórios
  issued_at    timestamptz NOT NULL DEFAULT now(),
  valid_until  date   NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Backfill: instâncias já aprovadas antes da feature ganham certificado
-- retroativo com issued_at = completed_at (data honesta da aprovação).
INSERT INTO eval_certificates (instance_id, verify_code, issued_at, valid_until)
SELECT ei.id,
       replace(gen_random_uuid()::text, '-', ''),
       COALESCE(ei.completed_at, now()),
       (COALESCE(c.end_date, COALESCE(ei.completed_at, now())::date) + interval '1 year')::date
  FROM eval_instances ei
  LEFT JOIN eval_cycles c ON c.id = ei.cycle_id
 WHERE ei.status IN ('aprovado', 'finalizado')
ON CONFLICT (instance_id) DO NOTHING;
