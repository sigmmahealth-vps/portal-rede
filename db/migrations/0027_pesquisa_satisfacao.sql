-- Pesquisa de Satisfação nativa (spec 5.4.6). Uma resposta por avaliação.
-- submitted_at registra o envio do roteiro (âncora do prazo de 7 dias).

ALTER TABLE eval_instances ADD COLUMN IF NOT EXISTS submitted_at timestamptz;

CREATE TABLE IF NOT EXISTS eval_survey_responses (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id     bigint NOT NULL UNIQUE REFERENCES eval_instances(id) ON DELETE CASCADE,
  q1_clareza      smallint,
  q2_portal       smallint,
  q3_documentos   text,
  q4_dificuldade  boolean,
  q4_texto        text,
  q5_geral        smallint,
  q6_nps          smallint,
  comentarios     text,
  submitted_at    timestamptz NOT NULL DEFAULT now(),
  within_deadline boolean NOT NULL,
  bonus_points    smallint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS eval_survey_responses_instance_idx
  ON eval_survey_responses (instance_id);
