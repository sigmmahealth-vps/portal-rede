-- 0030_notifications.sql
-- Notificações (spec 5.4.7). Uma linha por destinatário; a própria tabela é o
-- outbox de e-mail (email_status/email_attempts, retry no job horário).
-- user_id NULL = canal e-mail-apenas (ex.: roteiro_pendente); email_to NULL = só portal.

CREATE TABLE IF NOT EXISTS notifications (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint REFERENCES users(id) ON DELETE CASCADE,
  email_to       text,
  provider_id    bigint REFERENCES providers(id) ON DELETE CASCADE,
  type           text NOT NULL,
  title          text NOT NULL,
  body           text,
  link           text,
  dedupe_key     text UNIQUE,
  read_at        timestamptz,
  email_status   text NOT NULL DEFAULT 'na'
                   CHECK (email_status IN ('na','pendente','enviado','falhou')),
  email_attempts int NOT NULL DEFAULT 0,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS notifications_user_read_idx
  ON notifications (user_id, read_at) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS notifications_email_retry_idx
  ON notifications (email_status) WHERE email_status IN ('pendente','falhou');
