-- 0062_document_types.sql
-- Catálogo de tipos de documento (Gestão Documental, Parte 1), editável por admin.
-- documents.type_id passa a referenciar o catálogo; a coluna texto `type` fica por
-- compatibilidade (evidências de qualificação não têm type_id).

CREATE TABLE IF NOT EXISTS document_types (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        text NOT NULL UNIQUE,
  categoria   text CHECK (categoria IN ('obrigatoria','tecnica','regulatoria','contratual')),
  obrigatorio boolean NOT NULL DEFAULT false,
  escopo      text NOT NULL DEFAULT 'prestador' CHECK (escopo IN ('prestador','profissional')),
  ativo       boolean NOT NULL DEFAULT true,
  ordem       integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE documents ADD COLUMN IF NOT EXISTS type_id bigint REFERENCES document_types(id);
CREATE INDEX IF NOT EXISTS documents_type_id_idx ON documents (type_id);

