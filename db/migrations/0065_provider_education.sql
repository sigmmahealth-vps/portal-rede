-- 0065_provider_education.sql
-- Escolaridade autoinformada pelo prestador (por prestador), com arquivo e ciclo de validação.
CREATE TABLE IF NOT EXISTS provider_education (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id      bigint NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  nivel            text   NOT NULL CHECK (nivel IN
                     ('ensino_medio','tecnico','graduacao','especializacao','residencia','mestrado','doutorado','pos_doutorado')),
  curso            text,
  instituicao      text,
  conclusao_date   date,
  file_url         text,
  status           text   NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','valido','reprovado')),
  rejection_reason text,
  uploaded_by      bigint REFERENCES users(id),
  upload_date      timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS provider_education_provider_id_idx ON provider_education (provider_id);
